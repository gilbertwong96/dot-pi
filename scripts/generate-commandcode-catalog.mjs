#!/usr/bin/env node
/**
 * Snapshot the Command Code model catalog into the extension's baked-in seed list.
 *
 * The upstream /v1/models endpoint reports each model's `context_length`, but pi
 * only learns it from a live `refreshModels` call. Anything that reads the
 * provider before that call — a session start, an offline run, the model picker's
 * first paint — falls back to whatever this extension ships, so the seed has to
 * carry the real values or every model reports the 128K default.
 *
 * Regenerate after upstream adds or changes models:
 *
 *   node scripts/generate-commandcode-catalog.mjs
 *   npm run format
 *
 * The API key falls back to the `commandcode` entry in ~/.pi/agent/auth.json.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const BASE_URL = 'https://api.commandcode.ai/provider/v1'
const OUTPUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'extensions',
  'provider-commandcode-catalog.generated.ts'
)

function resolveApiKey() {
  if (process.env.COMMANDCODE_API_KEY) return process.env.COMMANDCODE_API_KEY
  const authPath = join(homedir(), '.pi', 'agent', 'auth.json')
  try {
    const auth = JSON.parse(readFileSync(authPath, 'utf8'))
    if (auth.commandcode?.key) return auth.commandcode.key
  } catch {
    // fall through to the error below
  }
  throw new Error('No API key: set COMMANDCODE_API_KEY or log in with /login')
}

/** Underscore-grouped literals match the surrounding source style. */
function formatNumber(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, '_')
}

async function fetchCatalog(apiKey) {
  const response = await fetch(`${BASE_URL}/models`, {
    signal: AbortSignal.timeout(60_000),
    headers: { Authorization: `Bearer ${apiKey}` }
  })
  if (!response.ok) throw new Error(`GET /models failed: HTTP ${response.status}`)
  const body = await response.json()
  const entries = Array.isArray(body.data) ? body.data : []
  return entries
    .filter((entry) => typeof entry?.id === 'string' && typeof entry?.context_length === 'number')
    .map((entry) => ({
      id: entry.id,
      name: typeof entry.name === 'string' && entry.name ? entry.name : entry.id,
      context_length: entry.context_length
    }))
    .sort((a, b) => a.id.localeCompare(b.id))
}

/** Keep every line inside the repo's 100-column print width so `npm run format:check` passes. */
function renderEntry(entry) {
  const fields = [
    ['id', JSON.stringify(entry.id)],
    ['name', JSON.stringify(entry.name)],
    ['context_length', formatNumber(entry.context_length)]
  ]
  const inline = `  { ${fields.map(([key, value]) => `${key}: ${value}`).join(', ')} },`
  if (inline.length <= 100) return inline
  return ['  {', ...fields.map(([key, value]) => `    ${key}: ${value},`), '  },'].join('\n')
}

function render(entries) {
  const lines = entries.map(renderEntry)
  return [
    '// Auto-generated by scripts/generate-commandcode-catalog.mjs',
    '// Do not edit manually. Regenerate with:',
    '//   node scripts/generate-commandcode-catalog.mjs && npm run format',
    `// Generated: ${new Date().toISOString()}`,
    `// Model count: ${entries.length}`,
    '',
    "import type { NormalizedOpenAIModel } from './shared/openai-models'",
    '',
    'export const COMMANDCODE_CATALOG: NormalizedOpenAIModel[] = [',
    ...lines,
    ']',
    ''
  ].join('\n')
}

const entries = await fetchCatalog(resolveApiKey())
if (entries.length === 0)
  throw new Error('Upstream returned no usable models; refusing to write an empty seed')
writeFileSync(OUTPUT, render(entries))
console.log(`Wrote ${entries.length} models to ${OUTPUT}`)
